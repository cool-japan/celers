#!/usr/bin/env python3
"""Re-capture the Celery wire fixtures committed under
``crates/celers-protocol/tests/fixtures``.

Run it whenever the pinned Celery version moves and ``test_envelope_golden.py``
starts failing::

    ./run.sh capture

What "capture" means here
-------------------------

The script takes the bytes Celery itself put on the wire and writes them out
unchanged, except for four **environment-specific substrings** that would
otherwise make the fixture machine-dependent (and would commit local paths and
a personal hostname into the repository):

===========================  ==========================================
substring                    replacement
===========================  ==========================================
the Python environment root  ``<python-env>``
the repository root          ``<repo>``
this machine's hostname      ``capture-host``
the capture queue name       left as ``celers-compat-capture`` (fixed)
===========================  ==========================================

Nothing about the *structure* is touched: no re-serialization, no key
reordering, no field removal. That is what makes the committed files evidence
rather than an assertion restated.

Identifiers are pinned where Celery lets a caller pin them (``task_id=``), so a
re-capture produces a minimal diff. ``reply_to`` and ``delivery_tag`` are
generated by kombu per process and will differ between runs; that is expected.
"""

from __future__ import annotations

import datetime
import json
import os
import pathlib
import socket
import sys
import uuid

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

#: The queue the capture publishes to. Fixed, so the ``delivery_info`` recorded
#: in every envelope is stable across re-captures.
CAPTURE_QUEUE = "celers-compat-capture"

#: What ``origin`` reports instead of the capturing machine's hostname.
CAPTURE_HOST = "capture-host"


def _bootstrap_env() -> None:
    url = os.environ.get("CELERS_TEST_REDIS_URL")
    if not url:
        print(
            "SKIPPED: capture_fixtures -- no Redis configured "
            "(set CELERS_TEST_REDIS_URL to run)",
            file=sys.stderr,
        )
        raise SystemExit(0)
    from urllib.parse import urlsplit, urlunsplit

    parts = urlsplit(url)
    db = os.environ.get("CELERS_COMPAT_REDIS_DB", "15")
    os.environ["CELERS_COMPAT_REDIS_URL"] = urlunsplit(
        (parts.scheme, parts.netloc, f"/{db}", parts.query, parts.fragment)
    )
    os.environ["CELERS_COMPAT_QUEUE"] = CAPTURE_QUEUE


_bootstrap_env()

import celery.utils.nodenames  # noqa: E402

# `origin` is `f"{pid}@{gethostname()}"`. Pin the host half before any task is
# published so the recorded header does not name the capturing machine.
celery.utils.nodenames.gethostname = lambda: CAPTURE_HOST  # type: ignore[assignment]

import harness  # noqa: E402

import celery  # noqa: E402
import kombu  # noqa: E402
from celery import chain, group  # noqa: E402
from celery.utils.saferepr import saferepr  # noqa: E402

import tasks  # noqa: E402

FIXTURES = harness.fixtures_dir()

#: Byte substitutions applied to every fixture, in order. Built at import time
#: because the paths are properties of *this* machine, not of Celery.
SUBSTITUTIONS: list[tuple[bytes, bytes]] = [
    (str(pathlib.Path(sys.prefix).resolve()).encode(), b"<python-env>"),
    (str(harness.REPO_ROOT).encode(), b"<repo>"),
    (socket.gethostname().encode(), CAPTURE_HOST.encode()),
]

#: Task ids pinned so a re-capture diffs cleanly.
FIXED_ID = "7b1a0d1e-0000-4000-8000-0000000000{:02d}"


def _normalize(raw: bytes) -> bytes:
    for needle, replacement in SUBSTITUTIONS:
        if needle:
            raw = raw.replace(needle, replacement)
    return raw


def _pop_verbatim(client) -> bytes:
    """Take the oldest queued message off the wire, exactly as kombu wrote it."""
    raw = client.rpop(CAPTURE_QUEUE)
    if raw is None:
        raise SystemExit(f"nothing was published to {CAPTURE_QUEUE}")
    return raw


def _write(name: str, payload: bytes) -> None:
    payload = _normalize(payload)
    path = FIXTURES / name
    path.write_bytes(payload if payload.endswith(b"\n") else payload + b"\n")
    print(f"wrote {path.relative_to(harness.REPO_ROOT)} ({len(payload)} bytes)")


def capture_envelopes(client) -> None:
    """One verbatim envelope per protocol feature the suite covers."""
    tasks.add.apply_async(args=[4, 5], queue=CAPTURE_QUEUE, task_id=FIXED_ID.format(1))
    _write("celery_task_v2_positional_list.json", _pop_verbatim(client))

    # `.delay()` keeps args as a tuple, which is what makes `argsrepr` read
    # "(4, 5)" rather than "[4, 5]". Both forms are real Celery output; CeleRS
    # emits the tuple form because `.delay()` is the canonical call.
    tasks.add.apply_async(args=(4, 5), queue=CAPTURE_QUEUE, task_id=FIXED_ID.format(2))
    _write("celery_task_v2_positional_tuple.json", _pop_verbatim(client))

    tasks.greet.apply_async(
        args=("Ada",),
        kwargs={"loud": True, "punct": "?"},
        queue=CAPTURE_QUEUE,
        task_id=FIXED_ID.format(3),
    )
    _write("celery_task_v2_kwargs.json", _pop_verbatim(client))

    tasks.add.apply_async(
        args=[1, 2], countdown=30, queue=CAPTURE_QUEUE, task_id=FIXED_ID.format(4)
    )
    _write("celery_task_v2_countdown.json", _pop_verbatim(client))

    eta = datetime.datetime(2030, 1, 2, 3, 4, 5, tzinfo=datetime.timezone.utc)
    expires = datetime.datetime(2030, 1, 2, 4, 4, 5, tzinfo=datetime.timezone.utc)
    tasks.add.apply_async(
        args=[1, 2],
        eta=eta,
        expires=expires,
        queue=CAPTURE_QUEUE,
        task_id=FIXED_ID.format(5),
    )
    _write("celery_task_v2_eta_expires.json", _pop_verbatim(client))

    chain(
        tasks.add.s(1, 2).set(task_id=FIXED_ID.format(6)),
        tasks.double.s().set(task_id=FIXED_ID.format(7)),
    ).apply_async(queue=CAPTURE_QUEUE)
    _write("celery_task_v2_chain_head.json", _pop_verbatim(client))

    group(
        tasks.add.s(1, 2).set(task_id=FIXED_ID.format(8)),
        tasks.add.s(3, 4).set(task_id=FIXED_ID.format(9)),
    ).apply_async(queue=CAPTURE_QUEUE)
    _write("celery_task_v2_group_member.json", _pop_verbatim(client))
    client.delete(CAPTURE_QUEUE)


def capture_results(client, worker_log: pathlib.Path) -> None:
    """Result records written by a *real* worker, not by the backend API."""
    with harness.CeleryWorker(CAPTURE_QUEUE, worker_log):
        ok_id = FIXED_ID.format(10)
        tasks.add.apply_async(args=[4, 5], queue=CAPTURE_QUEUE, task_id=ok_id)
        harness.await_result(client, ok_id)
        _write("celery_result_success.json", client.get(harness.result_key(ok_id)))
        client.delete(harness.result_key(ok_id))

        bad_id = FIXED_ID.format(11)
        tasks.boom.apply_async(
            args=["fixture failure"], queue=CAPTURE_QUEUE, task_id=bad_id
        )
        harness.await_result(client, bad_id)
        _write("celery_result_failure.json", client.get(harness.result_key(bad_id)))
        client.delete(harness.result_key(bad_id))


#: The (JSON value, Python repr) pairs CeleRS's ``argsrepr``/``kwargsrepr``
#: rendering must reproduce.
#:
#: Captured rather than assumed, because Celery renders these with
#: ``celery.utils.saferepr``, which is *not* the builtin ``repr``: it always
#: single-quotes a string and escapes an embedded ``'`` as ``\'`` where the
#: builtin would switch to double quotes, and it elides the contents of a
#: container opened at nesting level 3 or deeper.
REPR_ARGS = [
    [],
    [4, 5],
    ["Ada"],
    [1],
    [True, False, None],
    [1.5, 2.0, -0.25, 0.1],
    [1e16, 1e-5, 1e20, 1e-7, 123456789012345.0],
    # The exact points where Python's repr switches to exponent notation, from
    # both sides, plus negative zero. Off-by-one here is silent and invisible.
    [-0.0, 1e-4, 1e-5, 9.999e-5, 1e15, 1e16],
    ["it's", 'a"b', "plain", "back\\slash"],
    # saferepr passes control characters through literally rather than
    # escaping them the way the builtin repr would.
    ["line\nbreak", "tab\there", "cr\rhere"],
    [[1, 2], {"k": "v"}],
    [{"nested": {"deep": [1, None, True]}}],
    [{"a": {"b": {"c": {"d": 1}}}}],
    ["unicode: é and 日本"],
]

REPR_KWARGS = [
    {},
    {"loud": True},
    {"punct": "?"},
    {"a": None, "b": False},
    {"n": 1.0, "m": 2.5},
    {"quote": "it's"},
    {"nested": {"k": [1, 2]}},
    {"a": {"b": {"c": [1]}}},
    # A key needing the same quote escaping as a value.
    {"it's": 1, "plain": 2},
    # Control characters in a key, and an empty key.
    {"line\nbreak": 1, "": 2},
]


def capture_reprs() -> None:
    """Record what ``saferepr`` produces for every value CeleRS must render.

    Keys are sorted before the dict is reprd: a ``serde_json::Map`` is ordered,
    so CeleRS renders a dict with sorted keys, and comparing against an
    insertion-ordered Python repr would pin a difference CeleRS cannot close.
    The ordering caveat itself is asserted separately, in ``test_reprs.py``.
    """
    table = {
        "celery": celery.__version__,
        "kombu": kombu.__version__,
        "note": (
            "argsrepr renders args as a Python tuple; kwargsrepr renders a dict "
            "with keys sorted, because serde_json::Map is ordered."
        ),
        "args": [
            {"value": value, "repr": saferepr(tuple(value))} for value in REPR_ARGS
        ],
        "kwargs": [
            {"value": value, "repr": saferepr(_sorted_deep(value))}
            for value in REPR_KWARGS
        ],
    }
    _write(
        "celery_saferepr_table.json",
        json.dumps(table, indent=2, ensure_ascii=False).encode(),
    )


def _sorted_deep(value):
    """Rebuild ``value`` with every dict in sorted-key order."""
    if isinstance(value, dict):
        return {key: _sorted_deep(value[key]) for key in sorted(value)}
    if isinstance(value, list):
        return [_sorted_deep(item) for item in value]
    return value


def capture_celers_acceptance(client, worker_log: pathlib.Path) -> None:
    """Prove a CeleRS-built envelope runs on a real worker, then pin its bytes.

    The fixture is written only *after* the worker reports SUCCESS, so the
    committed bytes record something that demonstrably worked rather than a
    guess a later Rust test then rubber-stamps.
    """
    bridge = harness.bridge_path()
    if not bridge:
        print(
            "SKIPPED: CeleRS acceptance capture -- celery_bridge was not built "
            "(set CELERS_BRIDGE to run)",
            file=sys.stderr,
        )
        return

    task_id = FIXED_ID.format(12)
    envelope = harness.run_bridge(
        "encode-task",
        {"task": "tasks.add", "id": task_id, "args": [4, 5], "kwargs": {}},
    )
    payload = json.dumps(envelope, ensure_ascii=False).encode()

    with harness.CeleryWorker(CAPTURE_QUEUE, worker_log):
        client.lpush(CAPTURE_QUEUE, payload)
        meta = harness.await_result(client, task_id)

    client.delete(harness.result_key(task_id))
    if meta.get("status") != "SUCCESS" or meta.get("result") != 9:
        raise SystemExit(
            "a real Celery worker did not accept the CeleRS envelope: "
            f"{meta!r}\n{worker_log.read_text(errors='replace')}"
        )
    _write("celers_envelope_accepted_by_celery.json", payload)


def write_readme() -> None:
    """Record provenance next to the fixtures, so staleness is visible."""
    text = f"""# Verbatim Celery wire captures

Recorded by `tests/python-compat/capture_fixtures.py` from a **real** Python
Celery talking to a **real** Redis. Re-record them with:

```sh
CELERS_TEST_REDIS_URL=redis://127.0.0.1:6379 tests/python-compat/run.sh capture
```

| | |
|---|---|
| celery | {celery.__version__} |
| kombu | {kombu.__version__} |
| python | {sys.version.split()[0]} |
| task_protocol | 2 |
| serializer | json |

## What is in each file

| file | what it records |
|---|---|
| `celery_task_v2_positional_list.json` | `add.apply_async(args=[4, 5])` -- list `argsrepr` |
| `celery_task_v2_positional_tuple.json` | `add.apply_async(args=(4, 5))` -- tuple `argsrepr`, the `.delay()` form CeleRS emits |
| `celery_task_v2_kwargs.json` | keyword arguments, including a bool -- `kwargsrepr` with `True` |
| `celery_task_v2_countdown.json` | `countdown=30`, which Celery resolves to an `eta` header |
| `celery_task_v2_eta_expires.json` | explicit `eta` and `expires`, plus `properties.expiration` |
| `celery_task_v2_chain_head.json` | head of `chain(add.s(1, 2), double.s())` -- the `chain` embed |
| `celery_task_v2_group_member.json` | one member of a `group` -- the `group` and `group_index` headers |
| `celery_result_success.json` | result record a real worker wrote for a success |
| `celery_result_failure.json` | result record a real worker wrote for a raised `ValueError` |
| `celery_saferepr_table.json` | what `celery.utils.saferepr` renders for the values CeleRS must reproduce |
| `celers_envelope_accepted_by_celery.json` | a **CeleRS**-built envelope, recorded only after a real worker executed it |

## Normalization

The bytes are Celery's own, with four environment-specific substrings replaced
so the files are machine-independent:

* the Python environment root -> `<python-env>`
* the repository root -> `<repo>`
* the capturing machine's hostname -> `capture-host` (this reaches the `origin`
  header and the worker's node name)
* the queue is always `celers-compat-capture`, so `delivery_info` is stable

No structural change is made: no re-serialization, no key reordering, no
dropped fields. `reply_to` and `delivery_tag` are generated per process by
kombu and will differ between captures.
"""
    (FIXTURES / "README.md").write_text(text)
    print(f"wrote {(FIXTURES / 'README.md').relative_to(harness.REPO_ROOT)}")


def main() -> None:
    FIXTURES.mkdir(parents=True, exist_ok=True)
    client = harness.redis_client()
    log_dir = pathlib.Path(os.environ.get("TMPDIR", "/tmp"))
    worker_log = log_dir / f"celers-capture-{uuid.uuid4().hex[:8]}.log"
    try:
        capture_envelopes(client)
        capture_results(client, worker_log)
        capture_reprs()
        capture_celers_acceptance(client, worker_log)
        write_readme()
        print(
            f"\ncaptured with celery {celery.__version__}, "
            f"kombu {kombu.__version__}, python {sys.version.split()[0]}"
        )
    finally:
        client.delete(
            CAPTURE_QUEUE,
            f"_kombu.binding.{CAPTURE_QUEUE}",
            "unacked",
            "unacked_index",
            "unacked_mutex",
        )
        client.close()
        worker_log.unlink(missing_ok=True)


if __name__ == "__main__":
    main()
